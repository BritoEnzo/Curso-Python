print(12, 34, sep="-", end=";\n")  
print(56, 78, sep="-")

"""
print é uma função que tem como objetivo imprimir informações na tela.
dentro de um print, colocamos parâmetros, que são os valores que queremos imprimir, ou funções que queremos executar.

"""

"""
sep é um parâmetro da função print() que define o separador entre os valores que estão sendo impressos. 
Por padrão, o separador é um espaço em branco, mas podemos alterá-lo para qualquer outro caractere ou string que desejarmos.
No exemplo acima, estamos usando o hífen "-" como separador entre os números.
"""

"""
end é um parametro da função print() que define o que será impresso no final da linha, no exemplo acima, estamos usando o ponto e vírgula ";" 
seguido de uma quebra de linha "\n" como final da linha.
"""

